def run_holdout(fragments, embedding_index):
    """Возвращает ответы, ожидаемые выводы и контекст для проверки."""
    if embedding_index is None:
        raise ValueError("Сначала подключи индекс BGE-M3.")

    rows = []
    for name, question, expected, required in CASES:
        found = rag.search(question, fragments, embedding_index=embedding_index)
        answer = rag.ask_deepseek(question, found)
        missing = [
            f"{document}, п. {point}" if point else document
            for document, point in required
            if not any(document in fragment.document and point == fragment.point for fragment in found)
        ]
        rows.append({
            "test": name,
            "question": question,
            "expected": expected,
            "answer": answer,
            "missing_sources": "\n".join(missing),
            "context": "\n\n".join(
                f"{fragment.document}, п. {fragment.point}\n{fragment.text}" for fragment in found
            ),
        })
        print(f"Готово: {name}", flush=True)
    return rows
